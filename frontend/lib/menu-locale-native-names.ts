/** Nombre nativo del idioma para un locale BCP-47 (ej. en-US → English). */
export function nativeLocaleDisplayName(locale: string): string {
  const key = (locale || '').trim();
  if (!key) return '';
  if (NATIVE_BY_LOCALE[key]) return NATIVE_BY_LOCALE[key]!;
  const lang = key.split('-')[0]?.toLowerCase() || '';
  if (lang && NATIVE_BY_LANG[lang]) return NATIVE_BY_LANG[lang]!;
  return key;
}
